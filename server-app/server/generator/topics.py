def list_categories() -> List[str]:
    """返回十大板块列表（有序）。"""
    return list(CATEGORIES)


def get_topic(theme: str) -> Tuple[List[str], List[str]]:
    """返回指定主题的分论点方向与候选案例。

    非十大板块的主题返回空列表（由调用方校验，不应发生）。
    """
    if not is_valid_category(theme):
        return [], []
    return list(_SUB_POINT_HINTS.get(theme, [])), list(_CASE_POOL.get(theme, []))


def rotate_themes(count: int, start_index: int = 0) -> List[str]:
    """按板块顺序轮询取 count 个主题。

    start_index 指定起始位置，超出长度则取模，用于批次间错位轮换。
    """
    if count <= 0:
        return []
    n = len(CATEGORIES)
    if n == 0:
        return []
    start = start_index % n
    return [CATEGORIES[(start + i) % n] for i in range(count)]
